-- Per-test Playwright results (B-022).
--
-- A run's status alone cannot answer the questions the reports need: which tests
-- failed, how long each took, whether a failure was flaky, and which screenshot and
-- trace belong to *that* failure. All of that existed only inside a truncated stdout
-- blob, so it was unrecoverable once the run finished.
--
-- The DDL below is Hibernate's own output for this entity, generated against a real
-- PostgreSQL with the same procedure used for V1__baseline.sql, rather than
-- hand-transcribed. `ddl-auto=validate` on every profile then keeps it honest.
--
-- screenshot/video/trace paths are JSON arrays in TEXT rather than a child table:
-- they are only ever read as a complete list per test and never queried across
-- tests, so normalising them would add joins without buying anything.

create table test_case_result (
    ordinal_position integer not null,
    retries integer not null,
    duration_ms bigint,
    execution_id bigint not null,
    id bigint generated by default as identity,
    error_message TEXT,
    error_snippet TEXT,
    full_title varchar(255),
    screenshots TEXT,
    spec_file varchar(255),
    status varchar(255) not null,
    test_title varchar(255),
    traces TEXT,
    videos TEXT,
    primary key (id)
);

-- The report reads every result of one run in order, so the index is on
-- (execution_id) and the ordering is applied in the query.
create index idx_test_case_result_execution on test_case_result (execution_id);

alter table if exists test_case_result
    add constraint fk_test_case_result_execution
    foreign key (execution_id) references test_execution;
